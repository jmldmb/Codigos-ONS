def eh_dado_historico(ano: int, mes: int) -> bool:
    """
    Verifica se um dado ano/mês possui dados históricos reais.
    
    Retorna:
        True se há dados históricos reais
        False se é projeção
    """
    return ano in DADOS_HISTORICOS and mes in DADOS_HISTORICOS[ano]


